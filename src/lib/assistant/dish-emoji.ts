const RULES: [RegExp, string][] = [
  [/찌개|국|탕|전골|스프|수프/, "🍲"],
  [/면|파스타|스파게티|라면|우동|국수/, "🍜"],
  [/밥|덮밥|볶음밥|비빔밥|김밥|리조또/, "🍚"],
  [/치킨|닭/, "🍗"],
  [/고기|삼겹|스테이크|불고기|제육|돼지|소고기|갈비|스팸/, "🥩"],
  [/생선|연어|고등어|새우|해물|오징어|문어/, "🐟"],
  [/계란|달걀|오믈렛/, "🍳"],
  [/샐러드|나물|무침/, "🥗"],
  [/빵|토스트|샌드위치/, "🥪"],
  [/피자/, "🍕"],
  [/두부/, "🧈"],
  [/케이크|쿠키|디저트|베이킹/, "🍰"],
];

export function pickDishEmoji(text: string, fallback = "🍳") {
  return RULES.find(([re]) => re.test(text))?.[1] ?? fallback;
}
